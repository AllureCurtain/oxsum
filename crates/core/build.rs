//! Build-time codegen for the migration registry.
//!
//! `src/db.rs` embeds every migration with `include_str!` so a shipped binary carries its
//! own schema. The ordered list of `(version, sql)` pairs used to live as a hand-edited
//! array inside `db.rs`, which made it a merge hotspot: every migration-adding change to
//! one shared file, so parallel work collided on the array tail. Generating the array
//! here keeps the embedding semantics and the `_migrations` bookkeeping identical while
//! moving the registry out of any tracked source file — a new migration is now only a new
//! `migrations/NNNN_name.sql`, never an edit to a shared registry.

use std::error::Error;
use std::path::Path;
use std::{env, fs};

fn main() -> Result<(), Box<dyn Error>> {
    let manifest_dir = env::var("CARGO_MANIFEST_DIR")?;
    let migrations_dir = Path::new(&manifest_dir).join("migrations");
    println!("cargo:rerun-if-changed={}", migrations_dir.display());

    let mut entries: Vec<String> = fs::read_dir(&migrations_dir)?
        .map(|entry| entry.map(|e| e.path()))
        .collect::<Result<Vec<_>, _>>()?
        .into_iter()
        .filter(|path| path.extension().is_some_and(|ext| ext == "sql"))
        .map(|path| {
            let stem = path
                .file_stem()
                .and_then(|s| s.to_str())
                .map(str::to_owned)
                .ok_or("migration file has a non-utf-8 stem")?;
            // Absolute path so include_str! resolves regardless of OUT_DIR location.
            let absolute = path.canonicalize()?;
            Ok::<_, Box<dyn Error>>(format!(
                "    (\n        \"{stem}\",\n        include_str!(\"{}\"),\n    ),",
                absolute.display()
            ))
        })
        .collect::<Result<_, _>>()?;
    // Lexicographic order on file stems is also numeric order while every name is
    // zero-padded to four digits; db.rs keeps a runtime sorted-order guard as a backstop.
    entries.sort();

    let body = format!(
        "// @generated by crates/core/build.rs — do not edit.\n\
         const MIGRATIONS: &[(&str, &str)] = &[\n{}\n];\n",
        entries.join("\n")
    );
    let out_dir = env::var("OUT_DIR")?;
    fs::write(Path::new(&out_dir).join("migrations.rs"), body)?;
    Ok(())
}
