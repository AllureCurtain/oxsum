import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as api from 'verify-oxsum-bill';
import { inspect, scopedBill } from './scope.mjs';
const root=path.resolve(process.argv[2]??path.dirname(fileURLToPath(import.meta.url)));
const raw=(name)=>fs.readFileSync(path.join(root,name+'.json'),'utf8');
const data=(name)=>inspect(raw(name)).token(['data']);
let fetchAttempts=0;globalThis.fetch=()=>{fetchAttempts++;throw new Error('Offline verification forbids fetch');};
const bills=JSON.parse(data('bills')).rows.filter(b=>b.kind==='settlement');
const headRaw=data('signed-head'),head=JSON.parse(headRaw),keyRaw=data('operator-key');
const rejection=async(run)=>{try {await run();}catch(e){if(e instanceof TypeError||e instanceof ReferenceError)throw e;return {rejected:true,reason:e.message};}throw new Error('Altered input accepted');};
const results=[];
for(const bill of bills){
 const proofRaw=data('proof-'+bill.entryId),proof=inspect(proofRaw),description=JSON.parse(proof.get(['entry','description'])),sale=JSON.parse(proof.get(['sale','row']));
 const manifest={entryId:bill.entryId,contentHash:bill.contentHash,origin:head.origin,headSize:head.size,headRoot:head.root,priceVersion:description.priceVersion,sale:{bookId:sale.bookId,version:sale.version}};
 const manifestRaw=JSON.stringify(manifest);const run=(r=proofRaw,m=manifestRaw,h=headRaw,k=keyRaw)=>scopedBill(r,m,h,k,api);
 const verdict=await run();const price=await api.verifyPriceHead(proofRaw),saleVerdict=await api.verifySaleHead(proofRaw);assert.ok(price.ok&&saleVerdict.ok);
 const wrongHash=await rejection(()=>run(proofRaw,JSON.stringify({...manifest,contentHash:'0'.repeat(64)})));
 const altered=proof.replace(['entry','description'],JSON.stringify(JSON.stringify({...description,charged:description.charged+1})));
 const alteredCharge=await rejection(()=>run(altered));
 const wrongOrigin=await rejection(()=>run(proofRaw,JSON.stringify({...manifest,origin:'oxsum/ledgers/wrong'})));
 const wrongSaleVersion=await rejection(()=>run(proofRaw,JSON.stringify({...manifest,sale:{...manifest.sale,version:manifest.sale.version+1}})));
 const missingSale=await rejection(()=>run(proof.replace(['sale'],'null')));
 const wrongKey=await rejection(()=>run(proofRaw,manifestRaw,headRaw,JSON.stringify({...JSON.parse(keyRaw),publicKey:'0'.repeat(64)})));
 results.push({manifest,charge:description.charged,kind:description.kind,verdict,price,sale:saleVerdict,rejections:{wrongHash,alteredCharge,wrongOrigin,wrongSaleVersion,missingSale,wrongKey}});
}
assert.equal(results.length,6);assert.equal(results.filter(r=>r.charge===14).length,5);assert.equal(results.filter(r=>r.charge===0&&r.kind==='upstream_error').length,1);assert.equal(fetchAttempts,0);
fs.writeFileSync(path.join(root,'offline-verdicts.json'),JSON.stringify({fetchAttempts,results},null,2)+'\n');console.log(JSON.stringify({bills:results.length,positive:results.length,rejections:results.length*6,fetchAttempts}));
